#!/usr/bin/env python3
"""Build the data file the showcase page reads.

生成展示页读取的数据文件：字族、字重、文件大小、区块覆盖与逐字覆盖表。

The page must work from `file://` as well as GitHub Pages, so the data ships as
a plain script instead of a JSON fetched at runtime. Regenerate it whenever a
font is added or replaced.

页面既要能直接双击打开，也要能挂在 GitHub Pages 上，所以数据以普通脚本形式
随仓库发布，而不是运行时 fetch。新增或替换字体后重新运行本脚本。
"""

from __future__ import annotations

import json
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "fonts"
REPORT = ROOT / "docs" / "font-report.json"
OUT = ROOT / "data" / "font-data.js"

# Blocks shown in the glyph explorer. CJK is intentionally absent: there are no
# glyphs to list, and the page demonstrates the fallback instead.
# 字形浏览区展示的区块。中日韩区块故意不列：没有字形可列，页面直接演示回退。
CHAR_BLOCKS = {
    "basic-latin": (0x0020, 0x007E),
    "latin-1": (0x00A0, 0x00FF),
    "latin-ext-a": (0x0100, 0x017F),
    "greek": (0x0370, 0x03FF),
    "cyrillic": (0x0400, 0x04FF),
    "punctuation": (0x2000, 0x206F),
}


def chars_for(path: Path) -> dict[str, list[int]]:
    font = TTFont(path, lazy=True)
    cmap: set[int] = set()
    for table in font["cmap"].tables:
        if table.isUnicode():
            cmap.update(table.cmap.keys())
    result = {}
    for block, (start, end) in CHAR_BLOCKS.items():
        result[block] = [cp for cp in range(start, end + 1) if cp in cmap]
    return result


def main() -> None:
    report = json.loads(REPORT.read_text(encoding="utf-8"))
    families = []
    for family in report["families"]:
        entries = [f for f in report["fonts"] if f["family"] == family]
        by_style = {entry["style"].lower(): entry for entry in entries}
        regular = by_style.get("regular") or entries[0]
        chars = chars_for(FONT_DIR / regular["file"])
        families.append(
            {
                "name": family,
                "files": [
                    {
                        "file": entry["file"],
                        "style": entry["style"],
                        "weightClass": entry["weightClass"],
                        "bytes": entry["bytes"],
                        "license": entry["license"],
                        "glyphs": entry["glyphs"],
                        "mapped": entry["mappedCodepoints"],
                    }
                    for entry in entries
                ],
                "blocks": {
                    block["id"]: {"covered": block["covered"], "total": block["total"]}
                    for block in regular["blocks"]
                },
                "chars": chars,
            }
        )

    payload = {
        "schemaVersion": 1,
        "fontCount": report["fontCount"],
        "families": families,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "/* Generated by tools/build_site_data.py — do not edit by hand. */\n"
        "/* 由 tools/build_site_data.py 生成，请勿手工修改。 */\n"
        f"window.FONTKIT = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT} ({OUT.stat().st_size:,} bytes) / 已写入 {OUT}")


if __name__ == "__main__":
    main()
